export const ICON_SIZE = 16;

/** The painted pixels of an icon, ready for fillRect or SVG rects. */
export function iconPixels(
  instrument: Instrument
): Array<{ color: string; x: number; y: number }> {
  return INSTRUMENT_ICONS[instrument].flatMap((row, y) =>
    [...row].flatMap((key, x) => {
      const color = ICON_PALETTE[key];
      return color ? [{ x, y, color }] : [];
    })
  );
}
